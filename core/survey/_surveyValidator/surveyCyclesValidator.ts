import * as A from '@core/arena'

import { Dates } from '@openforis/arena-core'

import * as SurveyCycle from '../surveyCycle'
import type { SurveyCycle as SurveyCycleType } from '../surveyCycle'
import * as Validator from '../../validation/validator'
import * as Validation from '../../validation/validation'
import * as ValidationResult from '../../validation/validationResult'

import * as DateUtils from '../../dateUtils'

const MAX_CYCLES = 10

const _validateDate = (errorMessageKey: string) => (propName: string, obj: SurveyCycleType) => {
  const value = obj[propName]
  return value && !DateUtils.isValidDateInFormat(value, SurveyCycle.dateFormat)
    ? ValidationResult.newInstance(errorMessageKey)
    : null
}

const _validateDateIsBefore = (
  dateStr: string | null,
  dateToCompareStr: string | null,
  errorMessageKey: string
): ValidationResult.ValidationResultInstance | null => {
  if (!dateStr || !dateToCompareStr) {
    return null
  }

  const date = DateUtils.parse(dateStr, SurveyCycle.dateFormat)
  const dateToCompare = DateUtils.parse(dateToCompareStr, SurveyCycle.dateFormat)

  return Dates.isBefore(date, dateToCompare) ? null : ValidationResult.newInstance(errorMessageKey)
}

const _validateCycleStartDateBeforeEndDate = (_propName: string, item: SurveyCycleType) =>
  _validateDateIsBefore(
    SurveyCycle.getDateStart(item),
    SurveyCycle.getDateEnd(item),
    Validation.messageKeys.surveyInfoEdit.cycleDateStartBeforeDateEnd
  )

const _validateDateStartAfterPrevDateEnd = (cyclePrev: SurveyCycleType) => (_propName: string, item: SurveyCycleType) =>
  _validateDateIsBefore(
    SurveyCycle.getDateEnd(cyclePrev),
    SurveyCycle.getDateStart(item),
    Validation.messageKeys.surveyInfoEdit.cycleDateStartAfterPrevDateEnd
  )

const _cycleValidators = (cyclePrev: SurveyCycleType | null, isLast: boolean) => ({
  [SurveyCycle.keys.dateStart]: [
    Validator.validateRequired(Validation.messageKeys.surveyInfoEdit.cycleDateStartMandatory),
    _validateDate(Validation.messageKeys.surveyInfoEdit.cycleDateStartInvalid),
    _validateCycleStartDateBeforeEndDate,
    ...(cyclePrev ? [_validateDateStartAfterPrevDateEnd(cyclePrev)] : []),
  ],
  [SurveyCycle.keys.dateEnd]: [
    // Date end is required for all but the last cycle
    ...(isLast
      ? []
      : [Validator.validateRequired(Validation.messageKeys.surveyInfoEdit.cycleDateEndMandatoryExceptForLastCycle)]),
    _validateDate(Validation.messageKeys.surveyInfoEdit.cycleDateEndInvalid),
  ],
})

// true if the cycle keys are the consecutive numbers "0", "1"... (as generated by the survey info editor)
export const areCycleKeysValid = (cycles: Record<string, SurveyCycleType> | null | undefined): boolean =>
  Object.keys(cycles ?? {}).every((key, index) => key === String(index))

const _getCyclesErrorKey = (cycles: Record<string, SurveyCycleType>, cyclesSize: number): string | null => {
  if (cyclesSize === 0) return Validation.messageKeys.surveyInfoEdit.cyclesRequired
  if (cyclesSize > MAX_CYCLES) return Validation.messageKeys.surveyInfoEdit.cyclesExceedingMax
  // cycle keys are used as JSON keys and in queries
  if (!areCycleKeysValid(cycles)) return Validation.messageKeys.surveyInfoEdit.cycleKeysInvalid
  return null
}

export const validateCycles = async (
  cycles: Record<string, SurveyCycleType>
): Promise<Validation.ValidationInstance> => {
  const cyclesArray: SurveyCycleType[] = A.values(cycles)
  const cyclesSize = cyclesArray.length

  const result = Validation.newInstance()

  // 1. validate cycles size and keys
  const errorKey = _getCyclesErrorKey(cycles, cyclesSize)
  if (errorKey) {
    Validation.setErrors([ValidationResult.newInstance(errorKey)])(result)
    Validation.setValid(false)(result)
  }

  // 2. validate each cycle
  let cyclePrev: SurveyCycleType | null = null
  for (let index = 0; index < cyclesSize; index++) {
    const cycle = cyclesArray[index]

    const isLast = index === cyclesSize - 1
    const cycleValidation = await Validator.validate(cycle, _cycleValidators(cyclePrev, isLast)) // NOSONAR

    if (!Validation.isValid(cycleValidation)) {
      Validation.setField(String(index), cycleValidation)(result)
      Validation.setValid(false)(result)
    }

    cyclePrev = cycle
  }

  return result
}
